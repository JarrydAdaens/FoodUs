        vitaminB1 = vitaminB1.toNutrientValue(),
        vitaminB2 = vitaminB2.toNutrientValue(),
        vitaminB3 = vitaminB3.toNutrientValue(),
        vitaminB5 = vitaminB5.toNutrientValue(),
